package ru.mkilord.colortomqttapp.core.zone;

/**
 * Как обрабатывается цвет кадра перед отправкой.
 */
public enum ColorZone {
    /** Яркость ниже порога: отправляется яркость 0, светильник можно выключить. */
    BLACK,
    /** Насыщенность ниже порога: тон не важен, отправляется насыщенность 0. */
    GRAY,
    /** Обычный цвет: коррекция и ограничения применяются полностью. */
    COLOR
}
